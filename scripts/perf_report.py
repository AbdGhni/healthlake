"""Render docs/performance/results.md from the JSON measurement files in docs/performance/.

The tables are generated so that no number is copied by hand. Files read (those present are used):
  generation-<profile>.json  (scripts/measure.py output of `healthlake generate`)
  <profile>-cold.json, <profile>-warm.json  (scripts/perf_pipeline.py)
  api-<profile>-cold.json, api-<profile>-warm.json  (scripts/perf_api.py)
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
PERF = ROOT / "docs" / "performance"
PROFILES = ["demo", "extended"]
STEPS = ["archive", "adapt", "validate+resolve+classify", "normalize", "load", "finish"]


def load(name: str) -> dict[str, Any] | None:
    p = PERF / name
    return json.loads(p.read_text()) if p.exists() else None


def fmt(v: Any) -> str:
    if v is None:
        return "n/a"
    if isinstance(v, float):
        return f"{v:.2f}" if abs(v) < 10 else f"{v:.1f}"
    if isinstance(v, int):
        return f"{v:,}".replace(",", " ")
    return str(v)


def table(head: list[str], rows: list[list[Any]]) -> list[str]:
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    out += ["| " + " | ".join(fmt(c) for c in r) + " |" for r in rows]
    return [*out, ""]


def main() -> None:
    lines = [
        "# Performance results (generated)",
        "",
        "Generated by `scripts/perf_report.py` from the JSON files in this folder. Do not edit by hand.",
        "Protocol and analysis: [README.md](README.md).",
        "",
    ]
    gen_rows = []
    for prof in PROFILES:
        g = load(f"generation-{prof}.json")
        if g:
            gen_rows.append([prof, g["wall_s"], g["peak_rss_mb"], ", ".join(b[:12] for b in g.get("batch_ids", []))])
    if gen_rows:
        lines += ["## Generation (Synthea + derivation of CSV/JSON + manifests)", ""]
        lines += table(["Profile", "Wall (s)", "Peak RSS (MB)", "Batches (sha256 prefix)"], gen_rows)
    for prof in PROFILES:
        for mode in ("cold", "warm"):
            d = load(f"{prof}-{mode}.json")
            if not d:
                continue
            lines += [f"## Pipeline: {prof}, {mode}", ""]
            rows = []
            for b in d["batches"]:
                rows.append(
                    [
                        b["source_id"],
                        b["status"],
                        b["received"],
                        b["accepted"],
                        b["out_of_scope"],
                        b["rejected"],
                        b["wall_s"],
                        b["peak_rss_mb"],
                    ]
                    + [b["steps_s"].get(s) for s in STEPS]
                    + [b["work_dir_mb"]]
                )
            lines += table(
                ["Source", "Status", "Received", "Accepted", "Out of scope", "Rejected", "Wall (s)", "Peak RSS (MB)"]
                + [f"{s} (s)" for s in STEPS]
                + ["Work dir (MB)"],
                rows,
            )
            r = d["release"]
            lines += table(
                [
                    "Snapshot (s)",
                    "Members",
                    "dbt build (s)",
                    "dbt RSS (MB)",
                    "dbt docs (s)",
                    "Gate (s)",
                    "Publish (s)",
                    "Gate",
                ],
                [
                    [
                        r["build_snapshot_s"],
                        r["snapshot_members"],
                        r["dbt_build_s"],
                        r["dbt_build_peak_rss_mb"],
                        r["dbt_docs_s"],
                        r["quality_gate_s"],
                        r["publish_s"],
                        r["gate_status"],
                    ]
                ],
            )
            lines += table(["Gold table", "Rows"], [[k, v] for k, v in r["gold_rows"].items()])
            lines += table(
                ["Pipeline total (s)", "Database (MB)"] + [f"{k} (MB)" for k in d["dirs_mb"]],
                [[d["pipeline_total_s"], d["database_size_mb"], *d["dirs_mb"].values()]],
            )
    api_rows = []
    for prof in PROFILES:
        for mode in ("cold", "warm"):
            a = load(f"api-{prof}-{mode}.json")
            if a:
                api_rows.append(
                    [
                        prof,
                        mode,
                        a["clients"],
                        a["requests"],
                        a["errors"],
                        a["throughput_rps"],
                        a["aggregates_ms"]["p50"],
                        a["aggregates_ms"]["p95"],
                        a["aggregates_ms"]["p99"],
                        a["lists_ms"]["p50"],
                        a["lists_ms"]["p95"],
                        a["lists_ms"]["p99"],
                    ]
                )
    if api_rows:
        lines += ["## API (5 concurrent clients, client-side latency)", ""]
        lines += table(
            [
                "Profile",
                "Mode",
                "Clients",
                "Requests",
                "Errors",
                "Req/s",
                "Agg p50 (ms)",
                "Agg p95 (ms)",
                "Agg p99 (ms)",
                "List p50 (ms)",
                "List p95 (ms)",
                "List p99 (ms)",
            ],
            api_rows,
        )
        for prof in PROFILES:
            a = load(f"api-{prof}-warm.json")
            if a:
                lines += [f"### Per endpoint, {prof} warm", ""]
                lines += table(
                    ["Endpoint", "n", "p50 (ms)", "p95 (ms)"],
                    [[f"`{p}`", v["n"], v["p50"], v["p95"]] for p, v in a["per_endpoint_ms"].items()],
                )
    (PERF / "results.md").write_text("\n".join(lines).rstrip() + "\n")
    print(PERF / "results.md")


if __name__ == "__main__":
    main()
