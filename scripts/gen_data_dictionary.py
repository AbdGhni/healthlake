"""Render docs/data-dictionary.md from a migrated database with a published release.

Column names, types and nullability come from the live catalogue (information_schema), so the dictionary matches
what is deployed. Descriptions come from the dbt property files (Gold) and from the inline `--` comments of the
migrations (control, Bronze, Silver, quality).

  python scripts/gen_data_dictionary.py --dsn "host=... dbname=... user=..."     (needs PyYAML and psql)
"""

from __future__ import annotations

import argparse
import re
import subprocess
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
PLATFORM_SCHEMAS = ["ctl", "bronze", "silver", "quality"]
COL_LINE = re.compile(r"^\s+([a-z_][a-z0-9_]*)\s+[a-z].*?--\s*(.+)$")
TABLE_LINE = re.compile(r"^CREATE TABLE ([a-z_]+\.[a-z_]+)")


def psql(dsn: str, sql: str) -> list[list[str]]:
    out = subprocess.run(["psql", dsn, "-AtF", "\t", "-c", sql], capture_output=True, text=True, check=True).stdout
    return [line.split("\t") for line in out.splitlines() if line]


def migration_comments() -> dict[tuple[str, str], str]:
    found: dict[tuple[str, str], str] = {}
    for f in sorted((ROOT / "infrastructure" / "postgres" / "migrations").glob("*.sql")):
        table = None
        for line in f.read_text().splitlines():
            if m := TABLE_LINE.match(line):
                table = m.group(1)
            elif line.startswith(");"):
                table = None
            elif table and (m := COL_LINE.match(line)):
                found[(table, m.group(1))] = m.group(2).strip()
    return found


def dbt_docs() -> tuple[dict[str, str], dict[tuple[str, str], str]]:
    models: dict[str, str] = {}
    cols: dict[tuple[str, str], str] = {}
    for f in sorted((ROOT / "dbt" / "models").rglob("*.yml")):
        doc = yaml.safe_load(f.read_text()) or {}
        for m in doc.get("models", []):
            models[m["name"]] = m.get("description", "")
            for c in m.get("columns", []):
                cols[(m["name"], c["name"])] = c.get("description", "")
    return models, cols


def columns(dsn: str, schema: str) -> dict[str, list[tuple[str, str, str]]]:
    rows = psql(
        dsn,
        "SELECT table_name, column_name, data_type, is_nullable FROM information_schema.columns "
        f"WHERE table_schema = '{schema}' ORDER BY table_name, ordinal_position",
    )
    tables: dict[str, list[tuple[str, str, str]]] = {}
    for t, c, typ, nullable in rows:
        tables.setdefault(t, []).append((c, typ, "yes" if nullable == "YES" else "no"))
    return tables


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(dsn: str) -> str:
    gold_schema = psql(dsn, "SELECT r.schema_name FROM ctl.active_release a JOIN ctl.release r USING (release_id)")[0][
        0
    ]
    comments = migration_comments()
    model_desc, col_desc = dbt_docs()
    lines = [
        "# Data dictionary",
        "",
        "> HealthLake is a technical demonstration using synthetic data only.",
        "> It is not a certified healthcare platform and is not intended or",
        "> authorized to process real personal health data.",
        "",
        "Generated by `scripts/gen_data_dictionary.py` from a migrated database with a published release. Types and",
        "nullability come from the live catalogue; descriptions from the dbt property files (Gold) and the migration",
        "comments (platform schemas). Do not edit by hand. Diagrams: [architecture.md](architecture.md).",
        "",
        "## Gold (one schema per release, `release_<16 hex>`; the API reads the active one)",
        "",
    ]
    for table, cols in columns(dsn, gold_schema).items():
        lines += [
            f"### {table}",
            "",
            cell(model_desc.get(table, "")),
            "",
            "| Column | Type | Nullable | Description |",
            "|---|---|---|---|",
        ]
        lines += [f"| `{c}` | {t} | {n} | {cell(col_desc.get((table, c), ''))} |" for c, t, n in cols]
        lines.append("")
    lines += ["## Platform schemas", ""]
    for schema in PLATFORM_SCHEMAS:
        lines += [f"### Schema `{schema}`", ""]
        for table, cols in columns(dsn, schema).items():
            lines += [f"#### {schema}.{table}", "", "| Column | Type | Nullable | Note |", "|---|---|---|---|"]
            lines += [f"| `{c}` | {t} | {n} | {cell(comments.get((f'{schema}.{table}', c), ''))} |" for c, t, n in cols]
            lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--dsn", required=True)
    ap.add_argument("--out", default=str(ROOT / "docs" / "data-dictionary.md"))
    a = ap.parse_args()
    Path(a.out).write_text(render(a.dsn))
    print(a.out)


if __name__ == "__main__":
    main()
